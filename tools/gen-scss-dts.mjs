// *.module.scss から CSS Modules の型定義 (*.module.scss.d.ts) を生成する。
// Sass の modern API (sass.compile) でコンパイルし、クラス名を抽出する。
// usage: node tools/gen-scss-dts.mjs [rootDir=src]
//
// 制限: 正規表現による抽出のため、エスケープを含むクラス名と @keyframes 名は扱わない。
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const MODULE_SCSS_SUFFIX = '.module.scss';
const DTS_SUFFIX = '.d.ts';

// コンパイル済み CSS からローカルなクラス名を抽出する（重複なし・昇順）
export function extractClassNames(css) {
  const stripped = css
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'/g, '')
    .replace(/url\([^)]*\)/g, '')
    .replace(/\[[^\]]*\]/g, '')
    .replace(/:global\([^)]*\)/g, '');
  const names = new Set();
  // 宣言ブロック（{...} の中身）を除いたセレクタ部分のみを対象にする
  for (const selector of stripped.split(/\{[^{}]*\}/)) {
    for (const m of selector.matchAll(/\.(-?[_a-zA-Z][\w-]*)/g))
      names.add(m[1]);
  }
  return Array.from(names).sort();
}

export function renderDts(names) {
  return [
    '// This file is automatically generated by tools/gen-scss-dts.mjs.',
    '// Please do not change this file!',
    'interface CssExports {',
    ...names.map((n) => `  '${n}': string;`),
    '}',
    'declare const cssExports: CssExports;',
    'export default cssExports;',
    '',
  ].join('\n');
}

function listFiles(dir, suffix) {
  return fs
    .readdirSync(dir, { recursive: true })
    .map((f) => path.join(dir, f))
    .filter((f) => f.endsWith(suffix));
}

// rootDir 以下の型定義を生成・更新し、対応する scss がない型定義を削除する
export async function generate(rootDir, loadPaths = ['node_modules']) {
  const sass = await import('sass');
  const sources = listFiles(rootDir, MODULE_SCSS_SUFFIX);
  for (const file of sources) {
    const { css } = sass.compile(file, { loadPaths });
    const out = file + DTS_SUFFIX;
    const dts = renderDts(extractClassNames(css));
    if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== dts)
      fs.writeFileSync(out, dts);
  }
  const sourceSet = new Set(sources);
  for (const dts of listFiles(rootDir, MODULE_SCSS_SUFFIX + DTS_SUFFIX)) {
    if (!sourceSet.has(dts.slice(0, -DTS_SUFFIX.length))) fs.rmSync(dts);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url))
  await generate(process.argv[2] ?? 'src');
